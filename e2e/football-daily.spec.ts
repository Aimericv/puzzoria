import {expect,test} from "@playwright/test";
import {footballDailyCopy} from "../src/lib/football-daily-i18n";
import {generateDailyFootball} from "../src/lib/server/football-daily-content";
import {footballPlayers} from "../src/lib/server/knowledge-content";
import {kt} from "../src/lib/knowledge-i18n";
import {gamePath} from "../src/lib/i18n";
import {practicePath} from "../src/lib/play-path";
import {pg} from "../src/lib/post-game-i18n";
import {locales} from "../src/lib/types";
import {utcDay} from "../src/lib/date";
import {recordUnhandledRejections,unhandledRejections} from "./browser-errors";

for(const locale of locales)test(`harder football Daily in ${locale}: one official result, saved guesses, share and unlimited replay`,async({page},info)=>{
  const m=kt(locale),daily=footballDailyCopy(locale),date=utcDay(),privatePuzzle=generateDailyFootball(locale,date);
  await recordUnhandledRejections(page);
  await page.goto(gamePath(locale,"football"));
  const game=page.locator('[data-knowledge-game="football"]');
  await expect(game.locator('[data-football-mode="daily"]')).toContainText(daily.name);
  await expect(game.locator('.football-daily-clock b')).toHaveText(/\d{2}:\d{2}:\d{2}/);
  await expect(game.locator('.knowledge-start')).toContainText(daily.ready);
  const publicResponse=await page.request.get(`/api/challenges/${locale}/football`);
  expect(publicResponse.ok()).toBe(true);
  const publicPuzzle=await publicResponse.json();
  expect(publicPuzzle.id).toBe(privatePuzzle.id);expect(publicPuzzle.clubs).toEqual(privatePuzzle.clubs);
  expect(publicPuzzle.answer).toBeUndefined();expect(publicPuzzle.aliases).toBeUndefined();expect(publicPuzzle.sources).toBeUndefined();
  const before=await page.request.post('/api/play',{data:{action:'new',game:'football',locale,mode:'daily'}});
  const run=await before.json();
  await game.getByRole('button',{name:m.start,exact:true}).click();
  await expect(game.locator('.football-timeline')).toBeVisible();
  await page.screenshot({path:`test-results/football-daily-board-${locale}-${info.project.name}.png`,fullPage:true});
  await game.getByLabel(m.player,{exact:true}).fill('A wrong player');
  await game.getByRole('button',{name:m.submit,exact:true}).click();
  await expect(game.locator('.football-guesses li')).toHaveCount(1);
  await page.reload();await expect(game.locator('.football-guesses li')).toHaveCount(1);
  await game.getByLabel(m.player,{exact:true}).fill(privatePuzzle.aliases[0]);
  await game.getByRole('button',{name:m.submit,exact:true}).click();
  const result=game.locator('.completion-panel');await expect(result).toBeVisible();
  await expect(result.locator('[data-result-mode]')).toContainText(pg(locale).daily);
  await expect(result.locator('[data-result-metrics="football"]')).toContainText('2/6');
  await expect(result.locator('.football-reveal')).toContainText(privatePuzzle.answer);
  await result.locator('.share-button').click();
  await expect(result.locator('.share-text textarea')).toHaveValue(new RegExp(date));
  await expect(result.locator('.share-text textarea')).not.toHaveValue(new RegExp(privatePuzzle.answer));
  const otherLanguage=await page.request.post('/api/play',{data:{action:'new',game:'football',locale:locale==='fr'?'en':'fr',mode:'daily'}});
  const same=await otherLanguage.json();expect(same.runId).toBe(run.runId);expect(same.result.completion.mode).toBe('daily');
  await page.reload();await expect(result).toBeVisible();
  await result.locator('.result-play-actions .primary-button').click();
  await expect(page).toHaveURL(new RegExp(practicePath(locale,'football')+'$'));
  await expect(game.locator('[data-football-mode="practice"]')).toContainText(daily.unlimited);
  await expect(game.locator('.knowledge-start')).toBeVisible();
  await game.getByRole('button',{name:m.start,exact:true}).click();
  await expect(game.locator('.football-timeline')).toBeVisible();
  const clubs=await game.locator('.football-timeline strong').allTextContents();
  expect(footballPlayers.some(p=>JSON.stringify(p.clubs.map(s=>s.club))===JSON.stringify(clubs))).toBe(true);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:`test-results/football-daily-replay-${locale}-${info.project.name}.png`,fullPage:true});
  expect(await unhandledRejections(page)).toEqual([]);
});
