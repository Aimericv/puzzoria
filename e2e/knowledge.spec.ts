import { expect, test } from "@playwright/test";
import { kt } from "../src/lib/knowledge-i18n";
import { quizTopics, quizTopicPath } from "../src/lib/knowledge-catalog";
import { footballPlayers } from "../src/lib/server/knowledge-content";
import { rt } from "../src/lib/retention-i18n";
import { gamePath } from "../src/lib/i18n";
import { locales } from "../src/lib/types";
import { recordUnhandledRejections, unhandledRejections } from "./browser-errors";

for(const locale of locales) {
  test(`timed quiz in ${locale}: explicit start, accepted answers, reload, reveal, sharing and replay`,async({page},info)=>{
    const m=kt(locale), topic=quizTopics.find(t=>t.id==="planets")!;
    await recordUnhandledRejections(page);
    await page.goto(quizTopicPath(locale,topic));
    const game=page.locator('[data-knowledge-game="quiz"]');
    await expect(page.locator("h1")).toHaveText(topic.title[locale]);
    await expect(game.locator('[data-quiz-item]')).toHaveCount(0);
    const canonical=await page.locator('link[rel="canonical"]').getAttribute("href");
    expect(canonical).toContain(quizTopicPath(locale,topic));
    expect(await page.locator('link[rel="alternate"][hreflang]').count()).toBe(5);
    await game.getByRole("button",{name:m.start,exact:true}).click();
    await expect(game.locator('[data-quiz-item]')).toHaveCount(8);
    const input=game.getByLabel(m.answer,{exact:true});
    await input.fill("Mercury");
    // JetPunk-style automatic acceptance, without requiring a submit click.
    await expect(game.locator('[data-quiz-item="0"]')).toHaveClass(/found/);
    await page.reload();
    await expect(game.locator('[data-quiz-item="0"]')).toHaveClass(/found/);
    await input.fill("Venus");await game.getByRole("button",{name:m.submit,exact:true}).click();
    await expect(game.locator('[data-quiz-item="1"]')).toHaveClass(/found/);
    page.once("dialog",dialog=>dialog.accept());await game.getByRole("button",{name:m.finish,exact:true}).click();
    const result=game.locator(".completion-panel");await expect(result).toBeVisible();
    await expect(result.locator('[data-result-metrics="quiz"]')).toContainText("2/8");
    await expect(game.locator('[data-quiz-item]')).toHaveCount(8);
    await expect(game.locator('[data-quiz-item="2"]')).toHaveClass(/missed/);
    await expect(result.locator(".result-top-actions")).toBeVisible();
    await result.locator(".share-button").click();
    await expect(result.locator(".share-text textarea")).toHaveValue(new RegExp(quizTopicPath(locale,topic)));
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:`test-results/quiz-${locale}-${info.project.name}.png`,fullPage:true});
    const id=await page.locator('[data-game-root]').getAttribute("data-challenge-id");
    await result.getByRole("button",{name:rt(locale).playAgain,exact:true}).click();
    await expect(page.locator('[data-game-root]')).not.toHaveAttribute("data-challenge-id",id!);
    await expect(page.locator('[data-knowledge-game="quiz"] .knowledge-start')).toBeVisible();
    expect(await unhandledRejections(page)).toEqual([]);
  });
  test(`football in ${locale}: complete career, attempts, saved result and spoiler-free sharing`,async({page},info)=>{
    const m=kt(locale);await recordUnhandledRejections(page);
    await page.goto(gamePath(locale,"football"));const game=page.locator('[data-knowledge-game="football"]');
    await expect(game.locator(".football-timeline")).toHaveCount(0);
    await game.getByRole("button",{name:m.start,exact:true}).click();
    await expect(game.locator(".football-timeline")).toBeVisible();
    const clubs=await game.locator(".football-timeline strong").allTextContents();
    const player=footballPlayers.find(p=>JSON.stringify(p.clubs.map(c=>c.club))===JSON.stringify(clubs));expect(player).toBeDefined();
    const input=game.getByLabel(m.player,{exact:true});await input.fill("A wrong name");
    await game.getByRole("button",{name:m.submit,exact:true}).click();
    await expect(game.locator(".football-guesses li")).toHaveCount(1);
    await page.reload();await expect(game.locator(".football-guesses li")).toHaveCount(1);
    await input.fill(player!.aliases[0]);await game.getByRole("button",{name:m.submit,exact:true}).click();
    const result=game.locator(".completion-panel");await expect(result).toBeVisible();
    await expect(result.locator(".football-reveal")).toContainText(player!.name);
    await expect(result.locator('[data-result-metrics="football"]')).toContainText("2/6");
    await expect(game.locator(".football-timeline")).toBeVisible();
    await result.locator(".share-button").click();
    await expect(result.locator(".share-text")).toBeVisible();
    await expect(result.locator(".share-text")).not.toContainText(player!.name);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:`test-results/football-${locale}-${info.project.name}.png`,fullPage:true});
    expect(await unhandledRejections(page)).toEqual([]);
  });
}
